-- 0025: Current stock snapshot by lot
CREATE TABLE LOT_STOCK (
    lot_stock_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lot_id NUMBER NOT NULL,
    current_qty NUMBER DEFAULT 0 NOT NULL,
    reserved_qty NUMBER DEFAULT 0 NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT UQ_LOT_STOCK_LOT UNIQUE (lot_id),
    CONSTRAINT FK_LOT_STOCK_LOT FOREIGN KEY (lot_id) REFERENCES LOT(lot_id),
    CONSTRAINT CHK_LOT_STOCK_CURRENT_QTY CHECK (current_qty >= 0),
    CONSTRAINT CHK_LOT_STOCK_RESERVED_QTY CHECK (reserved_qty >= 0),
    CONSTRAINT CHK_LOT_STOCK_AVAILABLE CHECK (current_qty >= reserved_qty)
);
/
