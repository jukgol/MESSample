-- 0028: Backfill stock, history, and trace rows for existing lots
INSERT INTO LOT_STOCK (LOT_ID, CURRENT_QTY, RESERVED_QTY, UPDATED_AT, CREATED_AT)
SELECT L.LOT_ID, NVL(L.QTY, 0), 0, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
FROM LOT L
WHERE NOT EXISTS (
    SELECT 1
    FROM LOT_STOCK S
    WHERE S.LOT_ID = L.LOT_ID
);
/

INSERT INTO LOT_STOCK_HISTORY
    (LOT_ID, CHANGE_TYPE, BEFORE_QTY, CHANGE_QTY, AFTER_QTY, REASON, REF_TYPE, REF_ID, CREATED_AT)
SELECT L.LOT_ID, 'CREATE', 0, NVL(L.QTY, 0), NVL(L.QTY, 0), 'Backfilled from existing LOT', 'LOT', L.LOT_ID, CURRENT_TIMESTAMP
FROM LOT L
WHERE NOT EXISTS (
    SELECT 1
    FROM LOT_STOCK_HISTORY H
    WHERE H.LOT_ID = L.LOT_ID
      AND H.CHANGE_TYPE = 'CREATE'
);
/

INSERT INTO LOT_TRACE
    (PARENT_LOT_ID, CHILD_LOT_ID, TRACE_TYPE, INPUT_QTY, OUTPUT_QTY, PROCESS_STEP_EXECUTION_ID, REF_TYPE, REF_ID, CREATED_AT)
SELECT NULL, L.LOT_ID, 'BACKFILL', NULL, NVL(L.QTY, 0), NULL, 'LOT', L.LOT_ID, CURRENT_TIMESTAMP
FROM LOT L
WHERE NOT EXISTS (
    SELECT 1
    FROM LOT_TRACE T
    WHERE T.CHILD_LOT_ID = L.LOT_ID
      AND T.PARENT_LOT_ID IS NULL
      AND T.TRACE_TYPE = 'BACKFILL'
);
/
