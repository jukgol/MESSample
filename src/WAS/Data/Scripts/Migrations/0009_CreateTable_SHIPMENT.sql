-- 0009: SHIPMENT 테이블 생성 (출하 기록)
CREATE TABLE SHIPMENT (
    ship_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lot_id NUMBER NOT NULL,
    order_id VARCHAR2(50),
    qty NUMBER DEFAULT 0,
    shipped_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    
    CONSTRAINT FK_SHIP_LOT FOREIGN KEY (lot_id) REFERENCES LOT(lot_id)
);
