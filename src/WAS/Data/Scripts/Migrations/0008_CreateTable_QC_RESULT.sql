-- 0008: QC_RESULT 테이블 생성 (품질 검사 결과)
CREATE TABLE QC_RESULT (
    qc_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    log_id NUMBER NOT NULL,
    judgment VARCHAR2(10),
    defect_type VARCHAR2(50),
    action VARCHAR2(20),
    inspector VARCHAR2(50),
    memo CLOB,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    
    CONSTRAINT FK_QC_LOG FOREIGN KEY (log_id) REFERENCES PROCESS_LOG(log_id)
);
