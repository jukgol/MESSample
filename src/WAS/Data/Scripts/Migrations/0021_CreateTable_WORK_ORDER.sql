-- 0021: WORK_ORDER table for approved work orders
CREATE TABLE WORK_ORDER (
    work_order_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_order_no VARCHAR2(50) NOT NULL,
    process_master_id NUMBER NOT NULL,
    order_qty NUMBER NOT NULL,
    worker_user_id NUMBER,
    worker_name VARCHAR2(100),
    is_available CHAR(1) DEFAULT 'Y' NOT NULL,
    approved_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT UQ_WORK_ORDER_NO UNIQUE (work_order_no),
    CONSTRAINT FK_WORK_ORDER_PROCESS_MASTER FOREIGN KEY (process_master_id) REFERENCES PROCESS_MASTER(process_id),
    CONSTRAINT FK_WORK_ORDER_WORKER FOREIGN KEY (worker_user_id) REFERENCES USER_INFO(user_id),
    CONSTRAINT CHK_WORK_ORDER_AVAILABLE CHECK (is_available IN ('Y', 'N')),
    CONSTRAINT CHK_WORK_ORDER_QTY CHECK (order_qty > 0)
);
/
