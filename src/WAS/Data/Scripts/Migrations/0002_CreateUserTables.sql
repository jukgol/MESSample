-- 0002: 사용자 권한 및 정보 테이블 생성

-- 1. 권한 마스터 테이블
CREATE TABLE USER_ROLE (
    ROLE_CODE VARCHAR2(20) PRIMARY KEY,
    ROLE_NAME VARCHAR2(100) NOT NULL,
    DESCRIPTION VARCHAR2(255)
);
/

-- 2. 사용자 정보 테이블
CREATE TABLE USER_INFO (
    USER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    LOGIN_ID VARCHAR2(50) NOT NULL UNIQUE,
    PASSWORD VARCHAR2(255) NOT NULL,
    USER_NAME VARCHAR2(100) NOT NULL,
    ROLE_CODE VARCHAR2(20) NOT NULL,
    IS_ACTIVE CHAR(1) DEFAULT 'Y' NOT NULL,
    FAILED_LOGIN_COUNT NUMBER DEFAULT 0 NOT NULL,
    LAST_LOGIN_AT TIMESTAMP,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP,
    
    CONSTRAINT FK_USER_ROLE FOREIGN KEY (ROLE_CODE) REFERENCES USER_ROLE(ROLE_CODE),
    CONSTRAINT CHK_IS_ACTIVE CHECK (IS_ACTIVE IN ('Y', 'N'))
);
/

