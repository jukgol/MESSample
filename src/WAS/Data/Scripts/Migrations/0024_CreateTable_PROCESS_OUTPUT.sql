-- 0024: PROCESS_OUTPUT table for actual process outputs
CREATE TABLE PROCESS_OUTPUT (
    process_output_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    process_step_execution_id NUMBER NOT NULL,
    lot_id NUMBER NOT NULL,
    item_id NUMBER NOT NULL,
    target_qty NUMBER DEFAULT 0 NOT NULL,
    output_qty NUMBER NOT NULL,
    output_type VARCHAR2(30) DEFAULT 'GOOD' NOT NULL,
    output_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT FK_PROCESS_OUTPUT_EXECUTION FOREIGN KEY (process_step_execution_id) REFERENCES PROCESS_STEP_EXECUTION(process_step_execution_id),
    CONSTRAINT FK_PROCESS_OUTPUT_LOT FOREIGN KEY (lot_id) REFERENCES LOT(lot_id),
    CONSTRAINT FK_PROCESS_OUTPUT_ITEM FOREIGN KEY (item_id) REFERENCES ITEM(item_id),
    CONSTRAINT CHK_PROCESS_OUTPUT_TARGET_QTY CHECK (target_qty >= 0),
    CONSTRAINT CHK_PROCESS_OUTPUT_QTY CHECK (output_qty >= 0),
    CONSTRAINT CHK_PROCESS_OUTPUT_TYPE CHECK (output_type IN ('GOOD', 'DEFECT', 'LOSS'))
);
/
