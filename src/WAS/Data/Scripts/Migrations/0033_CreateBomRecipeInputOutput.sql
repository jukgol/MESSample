-- 0033: Create normalized BOM recipe/input/output tables and migrate existing BOM rows
CREATE TABLE BOM_RECIPE (
    bom_recipe_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_code VARCHAR2(120) NOT NULL,
    recipe_name VARCHAR2(100) NOT NULL,
    process_step_id NUMBER,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT FK_BOM_RECIPE_STEP FOREIGN KEY (process_step_id) REFERENCES PROCESS_STEP(step_id),
    CONSTRAINT UQ_BOM_RECIPE_CODE UNIQUE (recipe_code)
);
/

CREATE TABLE BOM_INPUT (
    bom_input_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bom_recipe_id NUMBER NOT NULL,
    item_id NUMBER NOT NULL,
    input_qty NUMBER NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT FK_BOM_INPUT_RECIPE FOREIGN KEY (bom_recipe_id) REFERENCES BOM_RECIPE(bom_recipe_id),
    CONSTRAINT FK_BOM_INPUT_ITEM FOREIGN KEY (item_id) REFERENCES ITEM(item_id),
    CONSTRAINT UQ_BOM_INPUT_RECIPE_ITEM UNIQUE (bom_recipe_id, item_id),
    CONSTRAINT CHK_BOM_INPUT_QTY CHECK (input_qty > 0)
);
/

CREATE TABLE BOM_OUTPUT (
    bom_output_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bom_recipe_id NUMBER NOT NULL,
    item_id NUMBER NOT NULL,
    output_qty NUMBER DEFAULT 1 NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT FK_BOM_OUTPUT_RECIPE FOREIGN KEY (bom_recipe_id) REFERENCES BOM_RECIPE(bom_recipe_id),
    CONSTRAINT FK_BOM_OUTPUT_ITEM FOREIGN KEY (item_id) REFERENCES ITEM(item_id),
    CONSTRAINT UQ_BOM_OUTPUT_RECIPE_ITEM UNIQUE (bom_recipe_id, item_id),
    CONSTRAINT CHK_BOM_OUTPUT_QTY CHECK (output_qty > 0)
);
/

INSERT INTO BOM_RECIPE (
    recipe_code,
    recipe_name,
    process_step_id
)
SELECT PI.ITEM_CODE || '_STEP_' || NVL(TO_CHAR(B.PROCESS_STEP_ID), 'NONE') AS recipe_code,
       PI.ITEM_NAME AS recipe_name,
       B.PROCESS_STEP_ID AS process_step_id
FROM BOM B
JOIN ITEM PI ON PI.ITEM_ID = B.PARENT_ITEM_ID
GROUP BY PI.ITEM_CODE,
         PI.ITEM_NAME,
         B.PROCESS_STEP_ID;
/

INSERT INTO BOM_INPUT (
    bom_recipe_id,
    item_id,
    input_qty
)
SELECT BR.BOM_RECIPE_ID,
       B.CHILD_ITEM_ID,
       B.BOM_QTY
FROM BOM B
JOIN ITEM PI ON PI.ITEM_ID = B.PARENT_ITEM_ID
JOIN BOM_RECIPE BR
  ON BR.RECIPE_CODE = PI.ITEM_CODE || '_STEP_' || NVL(TO_CHAR(B.PROCESS_STEP_ID), 'NONE')
GROUP BY BR.BOM_RECIPE_ID,
         B.CHILD_ITEM_ID,
         B.BOM_QTY;
/

INSERT INTO BOM_OUTPUT (
    bom_recipe_id,
    item_id,
    output_qty
)
SELECT BR.BOM_RECIPE_ID,
       B.PARENT_ITEM_ID,
       1 AS output_qty
FROM BOM B
JOIN ITEM PI ON PI.ITEM_ID = B.PARENT_ITEM_ID
JOIN BOM_RECIPE BR
  ON BR.RECIPE_CODE = PI.ITEM_CODE || '_STEP_' || NVL(TO_CHAR(B.PROCESS_STEP_ID), 'NONE')
GROUP BY BR.BOM_RECIPE_ID,
         B.PARENT_ITEM_ID;
/
