-- 0007: PROCESS_PARAM 테이블 생성 (공정 파라미터)
CREATE TABLE PROCESS_PARAM (
    param_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    log_id NUMBER NOT NULL,
    param_key VARCHAR2(50) NOT NULL,
    param_value VARCHAR2(100),
    unit VARCHAR2(20),
    
    CONSTRAINT FK_PARAM_LOG FOREIGN KEY (log_id) REFERENCES PROCESS_LOG(log_id)
);
