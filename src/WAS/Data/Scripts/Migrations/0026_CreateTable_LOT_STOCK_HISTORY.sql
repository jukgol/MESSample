-- 0026: Stock quantity change history by lot
CREATE TABLE LOT_STOCK_HISTORY (
    lot_stock_history_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lot_id NUMBER NOT NULL,
    change_type VARCHAR2(30) NOT NULL,
    before_qty NUMBER NOT NULL,
    change_qty NUMBER NOT NULL,
    after_qty NUMBER NOT NULL,
    reason VARCHAR2(200),
    ref_type VARCHAR2(50),
    ref_id NUMBER,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT FK_LOT_STOCK_HISTORY_LOT FOREIGN KEY (lot_id) REFERENCES LOT(lot_id),
    CONSTRAINT CHK_LOT_STOCK_HISTORY_TYPE CHECK (change_type IN ('CREATE', 'INCREASE', 'DECREASE', 'ADJUST', 'COMPLETE')),
    CONSTRAINT CHK_LOT_STOCK_HISTORY_BEFORE CHECK (before_qty >= 0),
    CONSTRAINT CHK_LOT_STOCK_HISTORY_AFTER CHECK (after_qty >= 0)
);
/
