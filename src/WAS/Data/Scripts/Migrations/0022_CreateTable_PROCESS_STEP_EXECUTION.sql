-- 0022: PROCESS_STEP_EXECUTION table for process monitoring
CREATE TABLE PROCESS_STEP_EXECUTION (
    process_step_execution_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_order_id NUMBER NOT NULL,
    process_step_id NUMBER NOT NULL,
    equipment_id VARCHAR2(50),
    worker_user_id NUMBER,
    status VARCHAR2(30) DEFAULT 'WAITING' NOT NULL,
    started_at TIMESTAMP,
    ended_at TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,

    CONSTRAINT FK_PSE_WORK_ORDER FOREIGN KEY (work_order_id) REFERENCES WORK_ORDER(work_order_id),
    CONSTRAINT FK_PSE_PROCESS_STEP FOREIGN KEY (process_step_id) REFERENCES PROCESS_STEP(step_id),
    CONSTRAINT FK_PSE_WORKER FOREIGN KEY (worker_user_id) REFERENCES USER_INFO(user_id),
    CONSTRAINT CHK_PSE_STATUS CHECK (status IN ('WAITING', 'RUNNING', 'PAUSED', 'DONE', 'FAILED'))
);
/
