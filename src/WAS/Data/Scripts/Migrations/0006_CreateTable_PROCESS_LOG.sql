-- 0006: PROCESS_LOG 테이블 생성 (공정 이력)
CREATE TABLE PROCESS_LOG (
    log_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lot_id NUMBER NOT NULL,
    step_id NUMBER NOT NULL,
    started_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    ended_at TIMESTAMP,
    operator VARCHAR2(50),
    equipment_id VARCHAR2(50),
    result VARCHAR2(30),
    memo CLOB,
    
    CONSTRAINT FK_LOG_LOT FOREIGN KEY (lot_id) REFERENCES LOT(lot_id),
    CONSTRAINT FK_LOG_STEP FOREIGN KEY (step_id) REFERENCES PROCESS_STEP(step_id)
);
/
