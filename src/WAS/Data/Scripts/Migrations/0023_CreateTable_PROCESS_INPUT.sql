-- 0023: PROCESS_INPUT table for actual process inputs
CREATE TABLE PROCESS_INPUT (
    process_input_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    process_step_execution_id NUMBER NOT NULL,
    lot_id NUMBER NOT NULL,
    item_id NUMBER NOT NULL,
    input_qty NUMBER NOT NULL,
    used_qty NUMBER DEFAULT 0 NOT NULL,
    remain_qty NUMBER NOT NULL,
    input_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT FK_PROCESS_INPUT_EXECUTION FOREIGN KEY (process_step_execution_id) REFERENCES PROCESS_STEP_EXECUTION(process_step_execution_id),
    CONSTRAINT FK_PROCESS_INPUT_LOT FOREIGN KEY (lot_id) REFERENCES LOT(lot_id),
    CONSTRAINT FK_PROCESS_INPUT_ITEM FOREIGN KEY (item_id) REFERENCES ITEM(item_id),
    CONSTRAINT CHK_PROCESS_INPUT_QTY CHECK (input_qty > 0),
    CONSTRAINT CHK_PROCESS_INPUT_USED_QTY CHECK (used_qty >= 0),
    CONSTRAINT CHK_PROCESS_INPUT_REMAIN_QTY CHECK (remain_qty >= 0)
);
/
