-- 0019: PROCESS_MASTER 테이블 생성 (공정 흐름 마스터)
CREATE TABLE PROCESS_MASTER (
    process_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    process_code VARCHAR2(50) NOT NULL,
    process_name VARCHAR2(100) NOT NULL,
    description CLOB,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT UQ_PROCESS_CODE UNIQUE (process_code)
);
/
