SELECT COLUMN_NAME as Name, DATA_TYPE as DataType, 
       CASE WHEN NULLABLE = 'Y' THEN 1 ELSE 0 END as IsNullable, 
       CASE WHEN IDENTITY_COLUMN = 'YES' THEN 1 ELSE 0 END as IsIdentity, 
       CASE WHEN DATA_DEFAULT IS NOT NULL THEN 1 ELSE 0 END as HasDefault
FROM ALL_TAB_COLUMNS 
WHERE OWNER = :SchemaName AND TABLE_NAME = :TableName
ORDER BY COLUMN_ID