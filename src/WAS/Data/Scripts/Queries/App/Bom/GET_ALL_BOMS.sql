SELECT B.BOM_ID AS BomID,
       B.PARENT_ITEM_ID AS ParentItemID,
       PI.ITEM_NAME AS ParentItemName,
       B.CHILD_ITEM_ID AS ChildItemID,
       CI.ITEM_NAME AS ChildItemName,
       B.BOM_QTY AS BomQty,
       B.PROCESS_STEP_ID AS ProcessStepID,
       P.STEP_NAME AS ProcessStepName
FROM BOM B
JOIN ITEM PI ON B.PARENT_ITEM_ID = PI.ITEM_ID
JOIN ITEM CI ON B.CHILD_ITEM_ID = CI.ITEM_ID
LEFT JOIN PROCESS_STEP P ON B.PROCESS_STEP_ID = P.STEP_ID
ORDER BY PI.ITEM_NAME ASC, B.BOM_ID ASC
