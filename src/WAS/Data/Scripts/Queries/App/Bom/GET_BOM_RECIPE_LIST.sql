SELECT BR.BOM_RECIPE_ID AS BomRecipeID,
       BR.RECIPE_CODE AS RecipeCode,
       BR.RECIPE_NAME AS RecipeName,
       BR.PROCESS_STEP_ID AS ProcessStepID,
       PS.STEP_NAME AS ProcessStepName,
       BR.CREATED_AT AS CreatedAt,
       BI.ITEM_ID AS InputItemID,
       II.ITEM_CODE AS InputItemCode,
       II.ITEM_NAME AS InputItemName,
       BI.INPUT_QTY AS InputQty,
       BO.ITEM_ID AS OutputItemID,
       OI.ITEM_CODE AS OutputItemCode,
       OI.ITEM_NAME AS OutputItemName,
       BO.OUTPUT_QTY AS OutputQty
FROM BOM_RECIPE BR
LEFT JOIN PROCESS_STEP PS ON PS.STEP_ID = BR.PROCESS_STEP_ID
LEFT JOIN BOM_INPUT BI ON BI.BOM_RECIPE_ID = BR.BOM_RECIPE_ID
LEFT JOIN ITEM II ON II.ITEM_ID = BI.ITEM_ID
LEFT JOIN BOM_OUTPUT BO ON BO.BOM_RECIPE_ID = BR.BOM_RECIPE_ID
LEFT JOIN ITEM OI ON OI.ITEM_ID = BO.ITEM_ID
ORDER BY BR.RECIPE_NAME ASC,
         BR.BOM_RECIPE_ID ASC,
         BI.BOM_INPUT_ID ASC,
         BO.BOM_OUTPUT_ID ASC
