SELECT B.BOM_ID,
       B.PARENT_ITEM_ID,
       PI.ITEM_NAME AS PARENT_ITEM_NAME,
       B.CHILD_ITEM_ID,
       CI.ITEM_NAME AS CHILD_ITEM_NAME,
       B.BOM_QTY
FROM BOM B
JOIN ITEM PI ON B.PARENT_ITEM_ID = PI.ITEM_ID
JOIN ITEM CI ON B.CHILD_ITEM_ID = CI.ITEM_ID
WHERE B.PARENT_ITEM_ID = :ParentItemId
ORDER BY B.BOM_ID ASC
