SELECT L.LOT_ID, 
       L.ITEM_ID, 
       I.ITEM_NAME, 
       L.LOT_NO, 
       L.QTY, 
       NVL(S.CURRENT_QTY, L.QTY) AS CURRENT_QTY,
       NVL(S.RESERVED_QTY, 0) AS RESERVED_QTY,
       NVL(S.CURRENT_QTY, L.QTY) - NVL(S.RESERVED_QTY, 0) AS AVAILABLE_QTY,
       L.RECEIVED_AT, 
       L.STATUS
FROM LOT L
JOIN ITEM I ON L.ITEM_ID = I.ITEM_ID
LEFT JOIN LOT_STOCK S ON S.LOT_ID = L.LOT_ID
ORDER BY L.LOT_ID DESC
