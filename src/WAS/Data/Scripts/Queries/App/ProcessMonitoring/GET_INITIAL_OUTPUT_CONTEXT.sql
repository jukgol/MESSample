SELECT WO.WORK_ORDER_NO AS WorkOrderNo,
       WO.ORDER_QTY AS OrderQty,
       MIN(BO.ITEM_ID) AS OutputItemID
FROM PROCESS_STEP_EXECUTION PSE
JOIN WORK_ORDER WO ON WO.WORK_ORDER_ID = PSE.WORK_ORDER_ID
JOIN BOM_RECIPE BR ON BR.PROCESS_STEP_ID = PSE.PROCESS_STEP_ID
JOIN BOM_OUTPUT BO ON BO.BOM_RECIPE_ID = BR.BOM_RECIPE_ID
WHERE PSE.PROCESS_STEP_EXECUTION_ID = :ExecutionId
GROUP BY WO.WORK_ORDER_NO,
         WO.ORDER_QTY
