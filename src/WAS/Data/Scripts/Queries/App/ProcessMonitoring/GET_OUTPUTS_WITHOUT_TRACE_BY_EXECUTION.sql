SELECT PI.LOT_ID AS ParentLotID,
       PO.LOT_ID AS ChildLotID,
       PI.INPUT_QTY AS InputQty,
       PO.OUTPUT_QTY AS OutputQty
FROM PROCESS_OUTPUT PO
JOIN PROCESS_INPUT PI ON PI.PROCESS_STEP_EXECUTION_ID = PO.PROCESS_STEP_EXECUTION_ID
WHERE PO.PROCESS_STEP_EXECUTION_ID = :ExecutionId
  AND NOT EXISTS (
      SELECT 1
      FROM LOT_TRACE LT
      WHERE LT.PARENT_LOT_ID = PI.LOT_ID
        AND LT.CHILD_LOT_ID = PO.LOT_ID
        AND LT.PROCESS_STEP_EXECUTION_ID = PO.PROCESS_STEP_EXECUTION_ID
        AND LT.TRACE_TYPE = 'PROCESS_OUTPUT'
  )
ORDER BY PO.PROCESS_OUTPUT_ID ASC,
         PI.PROCESS_INPUT_ID ASC
