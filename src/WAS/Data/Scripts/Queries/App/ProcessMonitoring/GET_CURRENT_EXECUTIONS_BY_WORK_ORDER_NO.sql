SELECT PSE.PROCESS_STEP_EXECUTION_ID AS ProcessStepExecutionID,
       PSE.WORK_ORDER_ID AS WorkOrderID,
       WO.WORK_ORDER_NO AS WorkOrderNo,
       WO.PROCESS_MASTER_ID AS ProcessMasterID,
       PM.PROCESS_NAME AS ProcessMasterName,
       WO.ORDER_QTY AS OrderQty,
       PSE.PROCESS_STEP_ID AS ProcessStepID,
       PS.STEP_NAME AS StepName,
       PS.SEQ_NO AS SeqNo,
       PSE.EQUIPMENT_ID AS EquipmentID,
       PSE.WORKER_USER_ID AS WorkerUserID,
       NVL(UI.USER_NAME, WO.WORKER_NAME) AS WorkerName,
       PSE.STATUS AS Status,
       PSE.STARTED_AT AS StartedAt,
       PSE.ENDED_AT AS EndedAt,
       WO.APPROVED_AT AS ApprovedAt,
       PSE.CREATED_AT AS CreatedAt,
       PSE.UPDATED_AT AS UpdatedAt
FROM PROCESS_STEP_EXECUTION PSE
JOIN WORK_ORDER WO ON PSE.WORK_ORDER_ID = WO.WORK_ORDER_ID
JOIN PROCESS_MASTER PM ON WO.PROCESS_MASTER_ID = PM.PROCESS_ID
JOIN PROCESS_STEP PS ON PSE.PROCESS_STEP_ID = PS.STEP_ID
LEFT JOIN USER_INFO UI ON PSE.WORKER_USER_ID = UI.USER_ID
WHERE WO.WORK_ORDER_NO = :WorkOrderNo
ORDER BY PS.SEQ_NO ASC, PSE.PROCESS_STEP_EXECUTION_ID ASC
